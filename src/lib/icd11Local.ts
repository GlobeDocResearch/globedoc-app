export function searchIcd11Local(query: string, limit = 8): Icd11LocalEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const starts: Icd11LocalEntry[] = [];
  const contains: Icd11LocalEntry[] = [];
  for (const entry of ICD11_LOCAL) {
    const t = entry.title.toLowerCase();
    if (t.startsWith(q)) starts.push(entry);
    else if (t.includes(q)) contains.push(entry);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
